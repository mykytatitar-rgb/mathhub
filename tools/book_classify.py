def _compile(p):
    return re.compile(p.replace(' ', r'\s*'), re.I) if p else None


COMPILED = [(r[0], _compile(r[1]), _compile(r[2]), r[3] if len(r) > 3 else 1.0) for r in RULES]

# Загальні назви, з яких тему не витягнеш — тут вирішує текст задачі.
GENERIC = re.compile(r'повторенн|вправи для|задачі підвищен|готуємося|олімпіад|повторение|review|miscellaneous|mixed', re.I)


def _title(t):
    return re.sub(r'^\s*(§\s*)?\d+\.\s*', '', t or '').strip()


def scores(point, para, text):
    point, para = _title(point), _title(para)
    if not point:
        # у книжці без пунктів найточніша назва — параграф
        point, para = para, ''
    s = {}
    point_generic = bool(GENERIC.search(point))
    for topic, head, body, weight in COMPILED:
        v = 0.0
        if point and not point_generic and head.search(point):
            v += 3
        if para and not GENERIC.search(para) and head.search(para):
            v += 1.2
        if text:
            if body is not None and body.search(text):
                v += 1.0
            elif head.search(text):
                v += 0.5
        if v:
            s[topic] = v * weight
    return s


def classify(point, para, text, subject=None, grade=None):
    """До двох тем карти, найімовірніша перша."""
    s = scores(point, para, text)
    if grade and grade <= 7:
        # у 7 класі системи лише лінійні, а комбінаторика — перебір і правила підрахунку
        if 'alg.nonlinsys' in s:
            s['alg.systems'] = max(s.get('alg.systems', 0), s.pop('alg.nonlinsys'))
        if 'disc.combschool' in s:
            s['disc.counting'] = max(s.get('disc.counting', 0), s.pop('disc.combschool'))
    for k in list(s):
        if subject == 'geo' and not k.startswith('geo.'):
            s[k] *= 0.6
        elif subject == 'alg' and k.startswith('geo.') and k not in ('geo.coords', 'geo.volumes'):
            s[k] *= 0.5
    if not s and para and point:
        # пункт нічого не підказав («Теореми») — беремо параграф як назву
        return classify('', para, text, subject, grade)
    if not s:
        return []
    ranked = sorted(s.items(), key=lambda kv: -kv[1])
    best = ranked[0][1]
    return [k for k, v in ranked[:2] if v >= best * 0.75 and v >= 1.0]
