/* Посилання учня, що потрапило в кабінет, — одразу на сторінку уроку.

   Посилання учня має вигляд …/share#<код репетитора>/<код уроку>. Сервер
   віддає кабінет на будь-яку незнайому адресу, тож спотворене посилання
   (/Share, обрізане месенджером «share») відкривало учневі кабінет із вікном
   входу. Код після # при цьому цілий — за ним і впізнаємо урок. Розділи
   кабінету починаються з «#/», тож їх це не зачіпає.

   Файл іде першим, до решти кабінету: учень не має побачити ні кабінету,
   ні вікна входу. */
(function () {
  'use strict';
  var m = /^#([0-9a-f-]{36}\/[0-9a-z]{16,})$/i.exec(location.hash || '');
  if (!m) return;
  location.replace(location.origin + location.pathname.replace(/[^/]*$/, '') + 'share#' + m[1]);
})();
